#this program is used to demonstrate the different data types in python
a = 10 #this is an integer
b = 3.14 #this is a float
c = "Hello, World!" #this is a string
#to check the data type of a variable, we can use the type() function
print(type(a)) # Output: <class 'int'>
print(type(b)) # Output: <class 'float'>
print(type(c)) # Output: <class 'str'>